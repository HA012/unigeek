inline bool builtinDictionary(const String& id, const uint8_t (**keys)[6], size_t* count, const char** label = nullptr) {
  if (id == kBuiltinDefaultId) { if (keys) *keys = kDefaultKeys; if (count) *count = kDefaultKeyCount; if (label) *label = "Default"; return true; }
  if (id == kBuiltinExtendedId) { if (keys) *keys = kExtendedKeys; if (count) *count = kExtendedKeyCount; if (label) *label = "Extended"; return true; }
  return false;
}

inline bool parseDictionaryKey(String line, uint8_t out[6]) {
  line.trim();
  if (!line.length() || line.startsWith("#")) return false;
  line.replace(":", "");
  line.replace(" ", "");
  if (line.length() != 12) return false;
  for (uint8_t i = 0; i < 6; ++i) {
    char pair[3] = {line[i * 2], line[i * 2 + 1], 0};
    char* end = nullptr;
    long value = strtol(pair, &end, 16);
    if (!end || *end) return false;
    out[i] = (uint8_t)value;
  }
  return true;
}

template <typename Fn>
inline size_t forEachDictionaryKey(IStorage* storage, const String& id, Fn fn) {
  const uint8_t (*builtin)[6] = nullptr;
  size_t builtinCount = 0;
  if (builtinDictionary(id, &builtin, &builtinCount)) {
    size_t visited = 0;
    for (size_t i = 0; i < builtinCount; ++i) {
      ++visited;
      if (!fn(builtin[i], i, builtinCount)) break;
    }
    return visited;
  }
  if (!storage || !storage->isAvailable()) return 0;
  fs::File f = storage->open(id.c_str(), FILE_READ);
  if (!f) return 0;
  size_t index = 0;
  while (f.available()) {
    String line = f.readStringUntil('\n');
    uint8_t key[6];
    if (!parseDictionaryKey(line, key)) continue;
    ++index;
    if (!fn(key, index - 1, 0)) break;
  }
  f.close();
  return index;
}

inline size_t dictionaryKeyCount(IStorage* storage, const String& id) {
  const uint8_t (*builtin)[6] = nullptr;
  size_t builtinCount = 0;
  if (builtinDictionary(id, &builtin, &builtinCount)) return builtinCount;
  size_t count = 0;
  forEachDictionaryKey(storage, id, [&](const uint8_t*, size_t, size_t) { ++count; return true; });
  return count;
}

inline String keyString(const uint8_t key[6]) {
  char out[13];
  snprintf(out, sizeof(out), "%02X%02X%02X%02X%02X%02X", key[0],key[1],key[2],key[3],key[4],key[5]);
  return String(out);
}

inline bool dictionaryContainsKey(IStorage* storage, const char* path, const uint8_t wanted[6]) {
  if (!storage || !storage->isAvailable()) return false;
  fs::File f = storage->open(path, FILE_READ);
  if (!f) return false;
  bool found = false;
  while (f.available()) {
    String line = f.readStringUntil('\n');
    uint8_t key[6];
    if (parseDictionaryKey(line, key) && memcmp(key, wanted, 6) == 0) {
      found = true;
      break;
    }
  }
  f.close();
  return found;
}

// Add every key present in the per-UID persisted-key buffer to the global
// discovered dictionary. The input format is: "Sxx A|B 12HEXCHARS".
// The existing dictionary is scanned line-by-line and new keys are appended;
// it is never loaded wholesale into RAM.
inline void updateDiscoveredDictionary(IStorage* storage, const String& persistedKeys) {
  if (!storage || !storage->isAvailable() || persistedKeys.length() == 0) return;

  storage->makeDir(kDictionaryDir);
  int start = 0;
  while (start < (int)persistedKeys.length()) {
    int nl = persistedKeys.indexOf('\n', start);
    if (nl < 0) nl = persistedKeys.length();
    String line = persistedKeys.substring(start, nl);
    line.trim();

    int sector = -1;
    char keyType = 0;
    char hex[13] = {};
    if (sscanf(line.c_str(), "S%d %c %12s", &sector, &keyType, hex) == 3) {
      uint8_t key[6];
      if (parseDictionaryKey(String(hex), key) &&
          !dictionaryContainsKey(storage, kDiscoveredDictionary, key)) {
        fs::File out = storage->open(kDiscoveredDictionary, FILE_APPEND);
        if (out) {
          out.println(keyString(key));
          out.close();
        }
      }
    }
    start = nl + 1;
  }
}

inline void saveUidKeys(IStorage* storage,
                        const uint8_t* uid, uint8_t uidLen, uint8_t sectors,
                        const bool foundA[40], const bool foundB[40],
                        const uint8_t keysA[40][6], const uint8_t keysB[40][6]) {
  if (!storage || !storage->isAvailable() || !uid || !uidLen || !sectors) return;
  if (sectors > 40) sectors = 40;

  storage->makeDir("/unigeek/nfc/keys");
  char uidHex[16] = {};
  for (uint8_t i = 0; i < uidLen && i * 2 + 2 < (int)sizeof(uidHex); i++) {
    char h[4];
    snprintf(h, sizeof(h), "%02X", uid[i]);
    strcat(uidHex, h);
  }
  String path = String("/unigeek/nfc/keys/") + uidHex + ".txt";
  String buf;
  for (uint8_t s = 0; s < sectors; s++) {
    char line[48];
    if (foundA[s]) {
      snprintf(line, sizeof(line), "S%02d A %02X%02X%02X%02X%02X%02X\n",
               s, keysA[s][0], keysA[s][1], keysA[s][2],
               keysA[s][3], keysA[s][4], keysA[s][5]);
      buf += line;
    }
    if (foundB[s]) {
      snprintf(line, sizeof(line), "S%02d B %02X%02X%02X%02X%02X%02X\n",
               s, keysB[s][0], keysB[s][1], keysB[s][2],
               keysB[s][3], keysB[s][4], keysB[s][5]);
      buf += line;
    }
  }
  if (buf.length() == 0) return;
  storage->writeFile(path.c_str(), buf.c_str());
  updateDiscoveredDictionary(storage, buf);
}

